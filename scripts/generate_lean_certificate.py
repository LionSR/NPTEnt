#!/usr/bin/env python3
"""Generate NPTEnt/Certificate/Blocks.lean from exact canonical-orbit JSON witnesses.

Reads data/certificates/canonical_orbits_{J_plus_Q,J_minus_Q,Q_gamma_in}.json
(15 canonical S_8-orbit blocks of sizes 1, 3, 6, 22, 42) and emits a self-contained
Lean module that kernel-checks every block via QICLean's fast QPair LDL checker
(`posSemidef_complex_of_checkLDLPairIntBool ... (by decide)`), with no `native_decide`
and no external trust assumptions.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data" / "certificates"
OUT_PATH = ROOT / "NPTEnt" / "Certificate" / "Blocks.lean"

TARGETS = [
    ("J_plus_Q", "canonical_orbits_J_plus_Q.json", "40(J+Q)"),
    ("J_minus_Q", "canonical_orbits_J_minus_Q.json", "40(J-Q)"),
    ("Q_gamma_in", "canonical_orbits_Q_gamma_in.json", "40 Q^{Gamma_in}"),
]

ORBITS = [
    ("(+1,-3)", "pos1_neg3"),
    ("(+1,-2,-1)", "pos1_neg2_neg1"),
    ("(+1,-1,-1,-1)", "pos1_neg1_neg1_neg1"),
    ("(-2)", "neg2"),
    ("(-1,-1)", "neg1_neg1"),
]


def fmt_vec(xs, render=str):
    return "![" + ", ".join(render(x) for x in xs) + "]"


def fmt_matrix(rows, render=str):
    return "![\n  " + ",\n  ".join(fmt_vec(row, render) for row in rows) + "]"


def fmt_pair(x):
    return f"⟨{x[0]}, {x[1]}⟩"


def generate_content() -> str:
    """Render the deterministic Lean witness module without writing files."""
    lines = [
        "/-",
        "Copyright (c) 2026 The NPTEnt contributors. All rights reserved.",
        "Released under Apache 2.0 license as described in the file LICENSE.",
        "Authors: The NPTEnt contributors",
        "-/",
        "import QICLean.Analysis.Order.RationalCertificate",
        "",
        "/-!",
        "# Kernel-Checked Canonical S_8-Orbit Blocks",
        "",
        "Generated by `scripts/generate_lean_certificate.py` from",
        "`data/certificates/canonical_orbits_{J_plus_Q,J_minus_Q,Q_gamma_in}.json`.",
        "",
        "Each of the 15 canonical S_8-orbit representative blocks (sizes 1, 3, 6, 22, 42",
        "for each of `40(J+Q)`, `40(J-Q)`, and `40 Q^{Gamma_in}`) is verified positive",
        "semidefinite directly in the Lean kernel using",
        "`QICLean.posSemidef_complex_of_checkLDLPairIntBool` and `by decide`",
        "(no `native_decide`, no external oracles).",
        "-/",
        "",
        "open Matrix QICLean",
        "open scoped ComplexOrder",
        "",
        "set_option linter.style.longLine false",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        "namespace NPTEnt.Certificate.Blocks",
        "",
    ]

    for target_name, json_name, label in TARGETS:
        data = json.loads((DATA_DIR / json_name).read_text())
        lines.append(f"section {target_name}")
        lines.append("")
        for orbit_key, orbit_ident in ORBITS:
            b = data["blocks"][orbit_key]
            n = b["size"]
            stem = f"{target_name}_{orbit_ident}"
            lines.append(
                f"/-- Canonical {orbit_key} ({n}×{n}) integer block of `{label}`. -/"
            )
            lines.append(f"def block_{stem} : Matrix (Fin {n}) (Fin {n}) ℤ :=")
            lines.append(fmt_matrix(b["matrix"]))
            lines.append("")
            lines.append(f"private def ldlL_{stem} : Matrix (Fin {n}) (Fin {n}) QPair :=")
            lines.append(fmt_matrix(b["L"], fmt_pair))
            lines.append("")
            lines.append(
                f"private def ldlD_{stem} : Fin {n} → QPair := "
                + fmt_vec(b["d"], fmt_pair)
            )
            lines.append("")
            lines.append(
                f"/-- Kernel-checked PSD proof for the {orbit_key} ({n}×{n}) block of `{label}`. -/"
            )
            lines.append(
                f"theorem block_{stem}_psd : (block_{stem}.map (Int.cast : ℤ → ℂ)).PosSemidef :="
            )
            lines.append(
                f"  posSemidef_complex_of_checkLDLPairIntBool ldlL_{stem} ldlD_{stem} (by decide)"
            )
            lines.append("")
        lines.append(f"end {target_name}")
        lines.append("")

    lines.append("end NPTEnt.Certificate.Blocks")
    lines.append("")

    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify that the committed module is current; write nothing")
    args = parser.parse_args(argv)
    content = generate_content()
    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text(encoding="utf-8") != content:
            print(f"Generated certificate module is not current: {OUT_PATH}")
            return 1
        print(f"Generated certificate module is current: {OUT_PATH}")
        return 0
    OUT_PATH.write_text(content, encoding="utf-8")
    nbytes = len(content.encode("utf-8"))
    nlines = content.count("\n")
    print(f"Wrote {OUT_PATH} ({nbytes} bytes, {nlines} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
