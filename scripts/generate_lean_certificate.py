#!/usr/bin/env python3
"""Generate the NPTEnt/Certificate/Blocks modules from exact canonical-orbit JSON witnesses.

Reads data/certificates/canonical_orbits_{J_plus_Q,J_minus_Q,Q_gamma_in}.json
(15 canonical S_8-orbit blocks of sizes 1, 3, 6, 22, 42) and emits Lean modules
that kernel-check every block via QICLean's fast QPair LDL checker
(`posSemidef_complex_of_checkLDLPairIntBool ... (by decide)`), with no `native_decide`
and no external trust assumptions.

The kernel check of a single 42×42 block needs roughly 11 GB of memory, and one
module holding all three exceeds 15 GB. Each 42×42 block therefore gets a module of
its own, and these modules import one another in a chain so that the build checks
them one after another instead of concurrently.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data" / "certificates"
OUT_PATH = ROOT / "NPTEnt" / "Certificate" / "Blocks.lean"
OUT_DIR = ROOT / "NPTEnt" / "Certificate" / "Blocks"
MODULE_PREFIX = "NPTEnt.Certificate.Blocks"
SMALL_MODULE = "Small"
HEAVY_SIZE = 42

TARGETS = [
    ("J_plus_Q", "canonical_orbits_J_plus_Q.json", "40(J+Q)", "JPlusQ"),
    ("J_minus_Q", "canonical_orbits_J_minus_Q.json", "40(J-Q)", "JMinusQ"),
    ("Q_gamma_in", "canonical_orbits_Q_gamma_in.json", "40 Q^{Gamma_in}", "QGammaIn"),
]

ORBITS = [
    ("(+1,-3)", "pos1_neg3"),
    ("(+1,-2,-1)", "pos1_neg2_neg1"),
    ("(+1,-1,-1,-1)", "pos1_neg1_neg1_neg1"),
    ("(-2)", "neg2"),
    ("(-1,-1)", "neg1_neg1"),
]

LICENSE_HEADER = [
    "/-",
    "Copyright (c) 2026 The NPTEnt contributors. All rights reserved.",
    "Released under Apache 2.0 license as described in the file LICENSE.",
    "Authors: The NPTEnt contributors",
    "-/",
]

GENERATED_NOTE = [
    "Generated by `scripts/generate_lean_certificate.py` from",
    "`data/certificates/canonical_orbits_{J_plus_Q,J_minus_Q,Q_gamma_in}.json`.",
]


def fmt_vec(xs, render=str):
    return "![" + ", ".join(render(x) for x in xs) + "]"


def fmt_matrix(rows, render=str):
    return "![\n  " + ",\n  ".join(fmt_vec(row, render) for row in rows) + "]"


def fmt_pair(x):
    return f"⟨{x[0]}, {x[1]}⟩"


def block_lines(target_name, label, orbit_key, orbit_ident, b):
    """Lean declarations for one canonical block and its kernel-checked PSD proof."""
    n = b["size"]
    stem = f"{target_name}_{orbit_ident}"
    return [
        f"/-- Canonical {orbit_key} ({n}×{n}) integer block of `{label}`. -/",
        f"def block_{stem} : Matrix (Fin {n}) (Fin {n}) ℤ :=",
        fmt_matrix(b["matrix"]),
        "",
        f"private def ldlL_{stem} : Matrix (Fin {n}) (Fin {n}) QPair :=",
        fmt_matrix(b["L"], fmt_pair),
        "",
        f"private def ldlD_{stem} : Fin {n} → QPair := " + fmt_vec(b["d"], fmt_pair),
        "",
        f"/-- Kernel-checked PSD proof for the {orbit_key} ({n}×{n}) block of `{label}`. -/",
        f"theorem block_{stem}_psd : (block_{stem}.map (Int.cast : ℤ → ℂ)).PosSemidef :=",
        f"  posSemidef_complex_of_checkLDLPairIntBool ldlL_{stem} ldlD_{stem} (by decide)",
        "",
    ]


def proof_module(import_name, title, description, sections):
    """A module of block proofs; `sections` is a list of (section name, declaration lines)."""
    lines = LICENSE_HEADER + [
        f"import {import_name}",
        "",
        "/-!",
        f"# {title}",
        "",
        *GENERATED_NOTE,
        "",
        *description,
        "-/",
        "",
        "open Matrix QICLean",
        "open scoped ComplexOrder",
        "",
        "set_option linter.style.longLine false",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        "namespace NPTEnt.Certificate.Blocks",
        "",
    ]
    for section_name, decls in sections:
        lines += [f"section {section_name}", "", *decls, f"end {section_name}", ""]
    lines += ["end NPTEnt.Certificate.Blocks", ""]
    return "\n".join(lines)


def generate_modules() -> dict:
    """Render every deterministic Lean witness module, keyed by output path, without writing."""
    small_sections = []
    heavy = []
    for target_name, json_name, label, module_stem in TARGETS:
        data = json.loads((DATA_DIR / json_name).read_text())
        small_decls = []
        for orbit_key, orbit_ident in ORBITS:
            b = data["blocks"][orbit_key]
            decls = block_lines(target_name, label, orbit_key, orbit_ident, b)
            if b["size"] >= HEAVY_SIZE:
                heavy.append((f"{module_stem}{b['size']}", target_name, label, orbit_key, decls))
            else:
                small_decls += decls
        small_sections.append((target_name, small_decls))

    modules = {}
    modules[OUT_DIR / f"{SMALL_MODULE}.lean"] = proof_module(
        "QICLean.Analysis.Order.RationalCertificate",
        "Kernel-Checked Canonical S_8-Orbit Blocks: Sizes 1, 3, 6, 22",
        [
            "The canonical S_8-orbit representative blocks of sizes 1, 3, 6 and 22 for each of",
            "`40(J+Q)`, `40(J-Q)`, and `40 Q^{Gamma_in}` are verified positive semidefinite",
            "directly in the Lean kernel using",
            "`QICLean.posSemidef_complex_of_checkLDLPairIntBool` and `by decide`",
            "(no `native_decide`, no external oracles).",
        ],
        small_sections,
    )
    previous = f"{MODULE_PREFIX}.{SMALL_MODULE}"
    chain = [previous]
    for module_name, target_name, label, orbit_key, decls in heavy:
        modules[OUT_DIR / f"{module_name}.lean"] = proof_module(
            previous,
            f"Kernel-Checked Canonical S_8-Orbit Block {orbit_key} of `{label}`",
            [
                f"The {HEAVY_SIZE}×{HEAVY_SIZE} canonical block of `{label}` is verified positive",
                "semidefinite directly in the Lean kernel using",
                "`QICLean.posSemidef_complex_of_checkLDLPairIntBool` and `by decide`",
                "(no `native_decide`, no external oracles).",
                "",
                "This check needs roughly 11 GB of memory. The import above is not needed for the",
                "proof: it orders the build so that the large blocks are checked one at a time.",
            ],
            [(target_name, decls)],
        )
        previous = f"{MODULE_PREFIX}.{module_name}"
        chain.append(previous)

    modules[OUT_PATH] = "\n".join(LICENSE_HEADER + [
        *(f"import {name}" for name in chain),
        "",
        "/-!",
        "# Kernel-Checked Canonical S_8-Orbit Blocks",
        "",
        *GENERATED_NOTE,
        "",
        "Each of the 15 canonical S_8-orbit representative blocks (sizes 1, 3, 6, 22, 42",
        "for each of `40(J+Q)`, `40(J-Q)`, and `40 Q^{Gamma_in}`) is verified positive",
        "semidefinite directly in the Lean kernel using",
        "`QICLean.posSemidef_complex_of_checkLDLPairIntBool` and `by decide`",
        "(no `native_decide`, no external oracles).",
        "",
        "The proofs live in the imported modules. The three 42×42 blocks each have a module",
        "of their own, imported in a chain, because one module holding all three does not",
        "fit in 15 GB of memory.",
        "-/",
        "",
    ])
    return modules


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify that the committed modules are current; write nothing")
    args = parser.parse_args(argv)
    modules = generate_modules()
    if args.check:
        stale = [path for path, content in modules.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        stale += [path for path in sorted(OUT_DIR.glob("*.lean")) if path not in modules]
        if stale:
            for path in stale:
                print(f"Generated certificate module is not current: {path}")
            return 1
        print(f"Generated certificate modules are current: {len(modules)} files")
        return 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path in sorted(OUT_DIR.glob("*.lean")):
        if path not in modules:
            path.unlink()
    for path, content in modules.items():
        path.write_text(content, encoding="utf-8")
        nbytes = len(content.encode("utf-8"))
        nlines = content.count("\n")
        print(f"Wrote {path} ({nbytes} bytes, {nlines} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
